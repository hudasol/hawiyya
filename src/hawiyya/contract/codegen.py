# ----------------------------------------------------------------------------- TypeScript


TS_RENAME = {"Record": "PatientRecord"}  # avoid shadowing the TypeScript Record<K, V> type


def _ts_name(name: str) -> str:
    return TS_RENAME.get(name, name)


def _ts_type(schema: dict[str, Any]) -> str:
    if "$ref" in schema:
        return _ts_name(str(schema["$ref"]).split("/")[-1])
    if "enum" in schema:
        return " | ".join(json.dumps(v) for v in schema["enum"])
    if "anyOf" in schema:
        parts = [_ts_type(s) for s in schema["anyOf"]]
        return " | ".join(dict.fromkeys(parts))
    t = schema.get("type")
    if t == "string":
        return "string"
    if t in ("number", "integer"):
        return "number"
    if t == "boolean":
        return "boolean"
    if t == "null":
        return "null"
    if t == "array":
        if "prefixItems" in schema:
            return "[" + ", ".join(_ts_type(s) for s in schema["prefixItems"]) + "]"
        inner = _ts_type(schema.get("items", {}))
        return f"({inner})[]" if "|" in inner else f"{inner}[]"
    if t == "object":
        extra = schema.get("additionalProperties")
        if isinstance(extra, dict):
            return f"Record<string, {_ts_type(extra)}>"
        return "Record<string, unknown>"
    return "unknown"


def _ts_decl(name: str, schema: dict[str, Any]) -> str:
    name = _ts_name(name)
    if "enum" in schema:
        return f"export type {name} = {_ts_type(schema)};\n"
    required = set(schema.get("required", []))
    lines = [f"export interface {name} {{"]
    for prop, sub in schema.get("properties", {}).items():
        opt = "" if prop in required else "?"
        lines.append(f"  {prop}{opt}: {_ts_type(sub)};")
    lines.append("}")
    return "\n".join(lines) + "\n"


def typescript() -> str:
    decls: dict[str, str] = {}
    for model in ALL_MODELS:
        schema = model.model_json_schema()
        for name, sub in schema.get("$defs", {}).items():
            decls[name] = _ts_decl(name, sub)
        decls[model.__name__] = _ts_decl(model.__name__, schema)
    body = "\n".join(decls[k] for k in sorted(decls))
    return HEADER_TS + "\n" + body


def artefacts() -> dict[Path, str]:
    out: dict[Path, str] = {}
    for name, schema in schemas().items():
        out[CONTRACT_DIR / "schema" / f"{name}.json"] = (
            json.dumps(schema, indent=2, ensure_ascii=False, sort_keys=True) + "\n"
        )
    out[CONTRACT_DIR / "field_dictionary.json"] = (
        json.dumps(field_dictionary(), indent=2, ensure_ascii=False) + "\n"
    )
    out[WEB / "src" / "contract" / "types.ts"] = typescript()
    return out


def stale_artefacts() -> list[Path]:
    return [
        p
        for p, text in artefacts().items()
        if not p.exists() or p.read_text(encoding="utf-8") != text
    ]


def write_artefacts() -> list[Path]:
    written = []
    for path, text in artefacts().items():
        if not path.exists() or path.read_text(encoding="utf-8") != text:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8", newline="\n")
            written.append(path)
    return written
