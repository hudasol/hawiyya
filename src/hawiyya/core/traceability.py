"""Requirement traceability: every MUST requirement is named by at least one test.

Requirements live in ``spec/requirements.json``. Tests name a requirement by writing its
identifier (for example ``HW-L4-005``) in the test source, usually through the
``pytest.mark.req`` marker. Python tests under ``tests/`` and web tests under ``web/`` are
scanned. Enforcement is progressive: a requirement is enforced once the phase that delivers
it is complete (``spec/phase.json``), so the build is honest about what exists at each gate.
"""

from __future__ import annotations

import json
import re
from dataclasses import dataclass
from pathlib import Path

from hawiyya.core.paths import DOCS, ROOT, SPEC

REQ_ID = re.compile(r"HW-(?:L[0-9]|X)-[0-9]{3}")
TIERS = ("MUST", "SHOULD", "MAY")
TEST_GLOBS = (
    ("tests", "**/*.py"),
    ("web/src", "**/*.test.ts"),
    ("web/src", "**/*.test.tsx"),
    ("web/e2e", "**/*.spec.ts"),
)


@dataclass(frozen=True)
class Requirement:
    id: str
    tier: str
    phase: int
    layer: str
    text: str


def load_requirements(path: Path | None = None) -> list[Requirement]:
    raw = json.loads((path or SPEC / "requirements.json").read_text(encoding="utf-8"))
    reqs = [Requirement(**item) for item in raw["requirements"]]
    for r in reqs:
        if not REQ_ID.fullmatch(r.id):
            raise ValueError(f"bad requirement id {r.id}")
        if r.tier not in TIERS:
            raise ValueError(f"bad tier for {r.id}")
    ids = [r.id for r in reqs]
    if len(ids) != len(set(ids)):
        raise ValueError("duplicate requirement ids")
    return reqs


def enforced_phase(path: Path | None = None) -> int:
    raw = json.loads((path or SPEC / "phase.json").read_text(encoding="utf-8"))
    return int(raw["completed_phase"])


def test_references(root: Path = ROOT) -> dict[str, list[str]]:
    """Map each requirement id to the test files that name it."""
    refs: dict[str, list[str]] = {}
    for base, pattern in TEST_GLOBS:
        folder = root / base
        if not folder.is_dir():
            continue
        for f in sorted(folder.glob(pattern)):
            if "node_modules" in f.parts:
                continue
            text = f.read_text(encoding="utf-8", errors="replace")
            rel = f.relative_to(root).as_posix()
            for rid in sorted(set(REQ_ID.findall(text))):
                refs.setdefault(rid, []).append(rel)
    return refs


def untested_musts(reqs: list[Requirement], refs: dict[str, list[str]], phase: int) -> list[str]:
    return [r.id for r in reqs if r.tier == "MUST" and r.phase <= phase and r.id not in refs]


def render_matrix(reqs: list[Requirement], refs: dict[str, list[str]], phase: int) -> str:
    lines = [
        "# Requirement traceability matrix",
        "",
        "Generated by `hawiyya docs build` from `spec/requirements.json` and the test sources.",
        "Do not edit by hand.",
        "",
        f"Requirements are enforced through phase P{phase}. A MUST requirement in an enforced",
        "phase without a naming test fails the build.",
        "",
        "| ID | Tier | Phase | Requirement | Tests | Status |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    for r in reqs:
        tests = refs.get(r.id, [])
        if tests:
            status = "tested"
        elif r.phase <= phase:
            status = "not tested" if r.tier == "MUST" else f"not tested ({r.tier})"
        else:
            status = "planned"
        shown = "<br>".join(f"`{t}`" for t in tests) if tests else ""
        lines.append(f"| {r.id} | {r.tier} | P{r.phase} | {r.text} | {shown} | {status} |")
    lines.append("")
    return "\n".join(lines)


def matrix_path() -> Path:
    return DOCS / "TRACEABILITY.md"
