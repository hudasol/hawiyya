"""Claims register: every public claim with its type and a pointer that must resolve.

Claims live in ``spec/claims.json`` and render to ``docs/CLAIMS.md``. Pointer kinds:

- ``context``: an anchor id that must appear in ``docs/CONTEXT.md`` as ``<a id="...">``.
- ``result``: ``results/<file>.json#/json/pointer`` that must exist.
- ``param``: ``module.path:ATTRIBUTE`` that must import and exist.
- ``file``: a repository path that must exist.
"""

from __future__ import annotations

import importlib
import json
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from hawiyya.core.paths import DOCS, ROOT, SPEC

CLAIM_TYPES = ("SOURCED", "SUPPORTED_BY_RESULT", "ASSUMPTION", "UNVERIFIED")
POINTER_KINDS = ("context", "result", "param", "file")


@dataclass(frozen=True)
class Claim:
    id: str
    text: str
    type: str
    kind: str | None
    ref: str | None
    where: str


def load_claims(path: Path | None = None) -> list[Claim]:
    raw = json.loads((path or SPEC / "claims.json").read_text(encoding="utf-8"))
    claims = [Claim(**c) for c in raw["claims"]]
    for c in claims:
        if c.type not in CLAIM_TYPES:
            raise ValueError(f"{c.id}: bad type {c.type}")
        if c.type != "UNVERIFIED" and (c.kind not in POINTER_KINDS or not c.ref):
            raise ValueError(f"{c.id}: a {c.type} claim needs a pointer")
    return claims


def json_pointer(doc: Any, pointer: str) -> Any:
    """Resolve an RFC 6901 JSON pointer, raising KeyError when it does not resolve."""
    if pointer in ("", "/"):
        return doc
    cur = doc
    for part in pointer.lstrip("/").split("/"):
        part = part.replace("~1", "/").replace("~0", "~")
        if isinstance(cur, list):
            cur = cur[int(part)]
        elif isinstance(cur, dict):
            cur = cur[part]
        else:
            raise KeyError(pointer)
    return cur


def resolve(claim: Claim, root: Path = ROOT) -> bool:
    """Return True when the claim's pointer resolves."""
    if claim.type == "UNVERIFIED" and claim.ref is None:
        return True
    assert claim.ref is not None
    try:
        if claim.kind == "context":
            text = (root / "docs" / "CONTEXT.md").read_text(encoding="utf-8")
            return f'<a id="{claim.ref}"></a>' in text
        if claim.kind == "result":
            file_part, _, pointer = claim.ref.partition("#")
            doc = json.loads((root / file_part).read_text(encoding="utf-8"))
            json_pointer(doc, pointer)
            return True
        if claim.kind == "param":
            module, _, attr = claim.ref.partition(":")
            return hasattr(importlib.import_module(module), attr)
        if claim.kind == "file":
            return (root / claim.ref).exists()
    except (OSError, KeyError, IndexError, ValueError, ImportError, json.JSONDecodeError):
        return False
    return False


def render_register(claims: list[Claim]) -> str:
    lines = [
        "# Claims register",
        "",
        "Generated by `hawiyya docs build` from `spec/claims.json`. Do not edit by hand.",
        "",
        "Every claim made in the README, the documents and the console copy is listed here",
        "with its type and a pointer. A test fails when a pointer does not resolve.",
        "",
        "Types: SOURCED (a public page opened during the build, listed in `docs/CONTEXT.md`),",
        "SUPPORTED_BY_RESULT (a file in `results/` produced by code in this repository),",
        "ASSUMPTION (a parameter chosen by the author), UNVERIFIED (stated, not checked).",
        "",
        "| ID | Claim | Type | Pointer | Where used |",
        "| --- | --- | --- | --- | --- |",
    ]
    for c in claims:
        pointer = f"{c.kind}: `{c.ref}`" if c.ref else ""
        lines.append(f"| {c.id} | {c.text} | {c.type} | {pointer} | {c.where} |")
    lines.append("")
    return "\n".join(lines)


def register_path() -> Path:
    return DOCS / "CLAIMS.md"
